import { expect, test } from '@playwright/test'
import { adminAPI, creds, signIn } from './helpers'

test('call entry: a call-taker enters, submits and keeps working the incident; a duplicate is offered first', async ({ page, request }) => {
  const api = await adminAPI(request)
  const first = await (await api.post('/incidents', { type: 'BURG', location: { address: '100 Test Ave', lat: 37.2711, lon: -79.9414 } })).json()
  const errors = await signIn(page, undefined, undefined, 'calltaker')
  await expect(page.getByRole('tablist', { name: 'Call entry tabs' })).toBeVisible()
  await page.fill('#ct-taker', 'burg')
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Weapons involved' }).click()
  await page.getByLabel('Latitude').fill('37.2712')
  await page.getByLabel('Longitude').fill('-79.9415')
  await page.getByLabel('Add to the narrative').fill('Caller hears glass breaking next door')
  await page.keyboard.press('Enter')
  await page.keyboard.press('F4')
  // The open burglary 15 m away is offered before a second incident.
  await expect(page.getByText('Is it one of these?')).toBeVisible()
  await expect(page.getByText(first.number).first()).toBeVisible()
  await page.keyboard.press('F4')
  await expect(page.getByText(/submitted: dispatch has it/)).toBeVisible()
  const num = (await page.locator('main span.font-mono.text-sm').first().innerText()).trim()
  // The workspace stays on it: a person on the Persons tab, a comment, the History tab.
  await page.getByRole('tab', { name: /Persons/ }).click()
  await page.getByRole('button', { name: 'Add a person' }).click()
  await page.getByLabel('New person').getByLabel('Name').fill('DOE, JOHN')
  await page.getByLabel('New person').getByRole('radio', { name: 'suspect' }).click()
  await page.getByLabel('New person').getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText('DOE, JOHN').first()).toBeVisible()
  await page.getByLabel('Add to the narrative').fill('Suspect left on foot')
  await page.keyboard.press('Enter')
  await page.getByRole('tab', { name: /History/ }).click()
  await expect(page.getByText('No unit sent yet.')).toBeVisible()
  const st = await api.get('/state')
  const inc = st.incidents.find((i: { number: string }) => i.number === num)
  expect(inc.modifiers).toContain('WEAPONS')
  expect(inc.persons[0].name).toBe('DOE, JOHN')
  expect(inc.timeline.some((t: { text: string }) => t.text.includes('glass breaking'))).toBeTruthy()
  // A call-taker cannot send units: the server says so.
  const r = await page.evaluate(async (n) => (await fetch(`./api/incidents/${n}/dispatch`, { method: 'POST', headers: { 'X-BitDispatcher': '1', 'Content-Type': 'application/json' }, body: JSON.stringify({ units: ['E1'], confirm: true }) })).status, num)
  expect(r).toBe(422)
  // F2 clears for the next call.
  await page.keyboard.press('F2')
  await expect(page.getByText('Not submitted')).toBeVisible()
  expect(errors).toEqual([])
})

test('the console locks and unlocks for the same person', async ({ page }) => {
  const { creds } = await import('./helpers')
  await signIn(page)
  await expect(page.getByText('911 CALLS')).toBeVisible()
  await page.keyboard.press('Control+Shift+L')
  await expect(page.getByRole('dialog', { name: /Locked/ })).toBeVisible()
  await page.getByLabel('Password').fill('not-the-password')
  await page.getByRole('button', { name: 'Unlock' }).click()
  await expect(page.getByRole('dialog', { name: /Locked/ }).getByRole('alert')).toBeVisible()
  await page.getByLabel('Password').fill(creds().password)
  await page.getByRole('button', { name: 'Unlock' }).click()
  await expect(page.getByRole('dialog', { name: /Locked/ })).toHaveCount(0)
  await expect(page.getByText('911 CALLS')).toBeVisible()
})

